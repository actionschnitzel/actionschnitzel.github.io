#!/usr/bin/env python3
"""Fetch the Steam Hardware Survey (Linux) and write it to _data/steam_survey.yml."""
import html
import json
import re
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

URL = "https://store.steampowered.com/hwsurvey/?platform=linux"
OUT = Path(__file__).resolve().parent.parent / "_data" / "steam_survey.yml"
USER_AGENT = "actionschnitzel.github.io survey sync (monthly, https://actionschnitzel.github.io)"

TAG = re.compile(r"<[^>]+>")
MONTH = re.compile(
    r"\b((?:January|February|March|April|May|June|July|August|September|October|November|December|"
    r"Januar|Februar|März|April|Mai|Juni|Juli|August|September|Oktober|November|Dezember)\s+\d{4})\b"
)


def clean(fragment: str) -> str:
    return " ".join(html.unescape(TAG.sub("", fragment)).split())


def fetch() -> str:
    request = urllib.request.Request(URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8", errors="replace")


def parse_distributions(page: str) -> list[dict]:
    start = page.find('id="cat0_details"')
    if start == -1:
        return []
    end = page.find('class="stats_row ', start)
    section = page[start:end if end != -1 else None]
    names = re.findall(r'<nobr>(.*?)</nobr>', section, re.S)
    shares = re.findall(r'<div class="stats_col_right data_row">(.*?)</div>', section, re.S)
    changes = re.findall(r'<div class="stats_col_right2 data_row">(.*?)</div>', section, re.S)
    distributions = [
        {"name": clean(name), "share": clean(share), "change": clean(change)}
        for name, share, change in zip(names, shares, changes)
    ]
    return sorted(distributions, key=lambda d: float(d["share"].rstrip("%")), reverse=True)


def write(month: str, distributions: list[dict]) -> None:
    lines = [
        f"# Generated by scripts/fetch_steam_survey.py on {datetime.now(timezone.utc):%Y-%m-%d}",
        f"source: {json.dumps(URL)}",
        f"month: {json.dumps(month)}",
        "distributions:",
    ]
    for dist in distributions:
        lines.append(f"  - name: {json.dumps(dist['name'], ensure_ascii=False)}")
        lines.append(f"    share: {json.dumps(dist['share'], ensure_ascii=False)}")
        lines.append(f"    change: {json.dumps(dist['change'], ensure_ascii=False)}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    page = fetch()
    month = MONTH.search(page)
    distributions = parse_distributions(page)
    if not month or not distributions:
        print("Month or distributions not found; page structure may have changed.", file=sys.stderr)
        return 1
    write(month.group(1), distributions)
    print(f"Wrote {len(distributions)} distributions to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
